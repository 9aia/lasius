#!/usr/bin/env python3
"""Generate docs/reference/config.md from config-struct doc comments
— the structs in lasius-core are the source of truth.

Migration note (myco T-065): the shared `cypera` tool
(../cypera — `cypera gen config`) scans `pub struct` doc comments,
but its page format has no marker splice and none of the curated
prose/type-name conventions below — this script stays until cypera
grows config-page splicing (or the page is restructured).
"""
import os, pathlib, re

# Sources live in the main checkout — normally docs/ is a worktree of it
# (so `..` works); in CI the docs sha runs detached, so LASIUS_ROOT
# points at the real repo.
ROOT = pathlib.Path(
    os.environ.get("LASIUS_ROOT") or pathlib.Path(__file__).parent / "..")
OUT  = pathlib.Path(__file__).parent / "reference" / "config.md"

# file → {struct: section title}; order preserved
SRCS = {
    "crates/lasius-core/src/config.rs": {
        "WorkspaceConfig": "Top level",
        "CheckConfig": "`[checks]` table",
        "Policy": "`[policy]` table",
    },
}
SRC = {n: (ROOT / f).read_text()
       for f, names in SRCS.items() for n in names}
TITLES = {n: t for names in SRCS.values() for n, t in names.items()}
STRUCTS = [n for names in SRCS.values() for n in names]

SIMPLE = {"String": "string", "PathBuf": "path", "bool": "bool",
          "u16": "int", "usize": "int", "u64": "int",
          "Vec<String>": "list", "Vec<PathBuf>": "list",
          "std::collections::BTreeMap<String, String>": "map",
          "std::collections::BTreeMap<String, UnitOverride>": "map"}

def fields(name):
    m = re.search(rf"pub struct {name} \{{(.*?)\n\}}", SRC[name], re.S)
    if not m: return []
    rows = []
    for fm in re.finditer(
            r"((?:\s*(?:///|#\[)[^\n]*\n)+)\s*"
            r"pub (\w+): ([^\n]+)", m.group(1)):
        prelude = fm.group(1)
        doc = " ".join(l.split("///", 1)[1].strip()
                       for l in prelude.splitlines() if "///" in l)
        fname, ty = fm.group(2), fm.group(3).strip().rstrip(",")
        opt = (ty.startswith("Option")
               or "serde(default" in prelude)
        inner = ty[7:-1] if ty.startswith("Option") else ty
        rows.append((fname, SIMPLE.get(inner, inner),
                     "" if opt else "required", doc or "—"))
    return rows

out = ["# Config — `lasius.toml`",
       "<!-- generated by gen-config-docs.py — edit the struct doc comments,",
       "     not this file -->", ""]
for name in STRUCTS:
    out += [f"## {TITLES[name]}", "",
            "| field | type | required | notes |",
            "|---|---|---|---|"]
    for fname, ty, req, doc in fields(name):
        doc = (doc.replace("|", "\\|")
                  .replace("<", "&lt;").replace(">", "&gt;"))
        out.append(
            f"| `{fname}` | `{ty}` | {req or 'optional'} | {doc} |")
    out.append("")
out += [
    "## Example", "",
    "```toml",
    'org = "9aia"',
    'repos_dir = "repos"',
    'exclude = ["workspace"]',
    "",
    "[checks]",
    "# disabled = [\"<check-id>\"]",
    'severity = { "<check-id>" = "warn" }',
    "",
    "[policy]",
    'require_worktrees = ["project", "docs"]',
    'require_files = ["AGENTS.md"]',
    "```", "",
    "## Constraints", "",
    "- `lasius.toml` is discovered by walking ancestors from the cwd",
    "  (or `--root <dir>`); every field except `org` has a default.",
    "- `provider` is a closed set — unknown values are a config error;",
    "  there is no silent fallback.",
    "- `exclude` entries are glob patterns (`*`, `?`) matched against",
    "  repo names.",
    "- Secret material never lives here.",
    "",
]
OUT.write_text("\n".join(out))
print(f"wrote {OUT}")
